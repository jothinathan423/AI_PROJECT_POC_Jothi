"""Steps 4-6 helpers: review gate blockers, proposal drafting from VERIFIED findings only, versions, commercial sheet, QA."""
import json
import re
from pathlib import Path

from sqlalchemy import func
from sqlalchemy.orm import Session

import llm
from models_v2 import Approval, CapabilityAssessment, Finding, Opportunity, ProposalVersion, RFI
from workflow import log

TEMPLATE = json.loads((Path(__file__).parent / "templates" / "proposal_template.json").read_text(encoding="utf-8"))
OPEN_RFI = ("draft", "approved", "sent")
PLACEHOLDER = re.compile(r"\[AB to [^\]]*\]", re.I)


def current_findings(db: Session, opp_id: int) -> list[Finding]:
    return db.query(Finding).filter(Finding.opp_id == opp_id, Finding.superseded.is_(False)).order_by(Finding.id).all()


def current_rfis(db: Session, opp_id: int) -> list[RFI]:
    return db.query(RFI).filter(RFI.opp_id == opp_id, RFI.superseded.is_(False)).order_by(RFI.id).all()


def effective_value(f: Finding) -> str:
    return f.corrected_value if f.review == "corrected" and f.corrected_value else f.value


def usable(db: Session, opp_id: int) -> list[Finding]:
    """Only reviewed findings may feed the proposal. Pending / disputed ones never become facts."""
    return [f for f in current_findings(db, opp_id) if f.review in ("verified", "corrected", "assumption")]


def g2_blockers(db: Session, opp_id: int) -> list[str]:
    out = []
    for f in current_findings(db, opp_id):
        if f.critical and f.review in ("pending", "disputed"):
            out.append(f"Critical {f.kind.replace('_', ' ')} #{f.id} is {f.review}: {f.value[:90]}")
    for r in current_rfis(db, opp_id):
        if r.priority == "High" and r.status == "draft":
            out.append(f"{r.rfi_no} (High) is still a draft - approve it for sending, or carry it as an assumption / dismiss it with a comment")
    return out


# ── commercial ─────────────────────────────────────────────────────────────

def commercial_total(c: dict) -> dict:
    lines = [l for l in (c or {}).get("lines", []) if isinstance(l, dict)]
    exp = [e for e in (c or {}).get("expenses", []) if isinstance(e, dict)]
    labour = round(sum(float(l.get("hours") or 0) * float(l.get("rate") or 0) for l in lines), 2)
    expenses = round(sum(float(e.get("amount") or 0) for e in exp), 2)
    sub = labour + expenses
    tax = round(sub * float((c or {}).get("tax_pct") or 0) / 100, 2)
    return {"labour": labour, "expenses": expenses, "subtotal": round(sub, 2), "tax": tax, "total": round(sub + tax, 2)}


def commercial_text(c: dict) -> str:
    t, cur = commercial_total(c), (c or {}).get("currency") or "USD"
    rows = [f"- {l.get('desc', '')}: {l.get('hours', 0)} h x {l.get('rate', 0)} = {round(float(l.get('hours') or 0) * float(l.get('rate') or 0), 2)} {cur}"
            for l in (c or {}).get("lines", [])]
    rows += [f"- Expense - {e.get('desc', '')}: {e.get('amount', 0)} {cur}" for e in (c or {}).get("expenses", [])]
    rows.append(f"Subtotal: {t['subtotal']} {cur} | Tax ({(c or {}).get('tax_pct') or 0}%): {t['tax']} {cur} | TOTAL: {t['total']} {cur}")
    rows.append("Fee inputs entered and approved by AB's authorised commercial lead; not generated by AI.")
    return "\n".join(rows)


# ── versions ───────────────────────────────────────────────────────────────

def latest_version(db: Session, opp_id: int) -> ProposalVersion | None:
    return db.query(ProposalVersion).filter(ProposalVersion.opp_id == opp_id).order_by(ProposalVersion.version_no.desc()).first()


def create_version(db: Session, opp: Opportunity, sections: list, compliance: list, created_by: str, note: str,
                   commercial: dict | None = None) -> ProposalVersion:
    prev = latest_version(db, opp.id)
    n = (prev.version_no if prev else 0) + 1
    if prev:
        prev.status = "superseded"
    pv = ProposalVersion(opp_id=opp.id, version_no=n, sections=sections, compliance=compliance,
                         commercial=commercial if commercial is not None else (prev.commercial if prev else {}),
                         status="draft", note=note, created_by=created_by)
    db.add(pv)
    db.flush()
    return pv


# ── drafting ───────────────────────────────────────────────────────────────

PROPOSAL_SYSTEM = """You draft sections of a civil-engineering proposal for AB Consultants from VERIFIED inputs only.
Each input has an ID like F123. Rules:
- Use only the supplied items. Cite the supporting ID in square brackets after each factual claim, e.g. [F12].
- Never invent quantities, fees, dates, deliverables that were not requested, team members or past experience.
- Where an input is an assumption or an RFI is still open, say the point is "subject to confirmation".
- Do not mention AI. Professional, plain, client-facing prose. Each section 90-220 words; bullets allowed where natural.
Return JSON: {"sections": [{"key": str, "content": str, "requirement_ids": [int]}]} for exactly these keys, in order: %s.
requirement_ids = the numeric IDs of REQUIREMENT items (not other items) that the section responds to."""
AI_KEYS = ["exec_summary", "understanding", "scope", "approach", "deliverables", "schedule", "quality_risk"]


def _assumptions_text(db: Session, opp: Opportunity, cap: CapabilityAssessment | None) -> str:
    rfis = current_rfis(db, opp.id)
    pend = [f for f in current_findings(db, opp.id) if f.review in ("pending", "disputed") and f.kind != "risk"]
    parts = ["Assumptions"] + [f"- {a}" for a in TEMPLATE["standard_assumptions"]]
    parts += [f"- {r.rfi_no}: {r.issue} (carried as an assumption)" for r in rfis if r.status == "assumption"]
    dep = [r for r in rfis if r.status in OPEN_RFI]
    if dep:
        parts += ["", "Dependencies and open clarifications"] + [f"- {r.rfi_no} [{r.priority}] {r.issue}" for r in dep]
    if cap and cap.decision == "conditional_go" and cap.decision_conditions:
        parts += ["", "Internal conditions of the bid decision (remove before release if not for client view)",
                  f"- {cap.decision_conditions}"]
    if pend:
        parts += ["", f"{len(pend)} extracted item(s) were not verified by the engineering reviewer and were excluded from this proposal."]
    parts += ["", "Exclusions"] + [f"- {x}" for x in TEMPLATE["standard_exclusions"]]
    return "\n".join(parts)


async def run_proposal(db: Session, opp: Opportunity, actor_name: str = "system") -> ProposalVersion:
    ok = usable(db, opp.id)
    if not ok:
        raise RuntimeError("No verified findings to draft from - the engineering reviewer must verify at least the key RFQ items.")
    cap = db.query(CapabilityAssessment).filter(CapabilityAssessment.opp_id == opp.id).order_by(CapabilityAssessment.run_no.desc()).first()
    items = [{"id": f.id, "kind": f.kind, "name": f.key, "text": effective_value(f)[:500],
              "mandatory": bool(f.critical and f.kind == "requirement"), "review": f.review,
              "source": f"{f.source_file} p.{f.source_page}" if f.source_file else ""} for f in ok]
    open_rfis = [{"no": r.rfi_no, "priority": r.priority, "issue": r.issue, "status": r.status, "response": r.response[:300]}
                 for r in current_rfis(db, opp.id) if r.status not in ("dismissed",)]
    log(db, opp.id, "proposal", f"Drafting from {len(items)} verified item(s); {len(open_rfis)} RFI(s) considered…")
    db.commit()
    out = await llm.chat_json(PROPOSAL_SYSTEM % ", ".join(AI_KEYS), json.dumps(
        {"project": {"name": opp.project_name, "client": opp.client, "deadline": opp.submission_deadline},
         "verified_items": items, "rfis": open_rfis,
         "bid_conditions": cap.decision_conditions if cap and cap.decision == "conditional_go" else ""})[:60000], max_tokens=7000)
    ai = {s.get("key"): s for s in out.get("sections", []) if isinstance(s, dict)}
    valid_ids = {f.id for f in ok}
    req_ids = {f.id for f in ok if f.kind == "requirement"}

    sections, n = [], 0
    for t in TEMPLATE["sections"]:
        n += 1
        sec = {"key": t["key"], "number": n, "title": t["title"], "source": t["source"], "content": "",
               "finding_ids": [], "requirement_ids": [], "placeholder": False, "edited_by": ""}
        if t["key"] == "cover":
            sec["content"] = (f"Client: {opp.client or '[AB to enter]'}\nProject: {opp.project_name or '[AB to enter]'}\n"
                              f"Procurement reference: {opp.rfq_reference or '[AB to enter]'}\nSubmission deadline: {opp.submission_deadline or '[AB to enter]'}\n"
                              "Authorised signatory: [AB to enter name and title]")
        elif t["key"] == "team":
            sec["content"] = TEMPLATE["team_placeholder"]
        elif t["key"] == "commercial":
            sec["content"] = TEMPLATE["commercial_placeholder"]
        elif t["key"] == "assumptions":
            sec["content"] = _assumptions_text(db, opp, cap)
        else:
            raw = ai.get(t["key"], {})
            text = str(raw.get("content", "")).strip() or "[AB to complete: the AI draft returned no content for this section.]"
            cited = {int(x) for x in re.findall(r"\[F(\d+)\]", text)}
            bad = cited - valid_ids
            for b in bad:     # a citation to something that is not a verified finding is removed, not trusted
                text = text.replace(f"[F{b}]", "")
            sec["content"] = text
            sec["finding_ids"] = sorted(cited & valid_ids)
            sec["requirement_ids"] = sorted({int(i) for i in raw.get("requirement_ids", []) if str(i).isdigit()} & req_ids)
            if bad:
                sec["unsupported_citations"] = sorted(bad)
        sec["placeholder"] = bool(PLACEHOLDER.search(sec["content"]))
        sections.append(sec)

    compliance = []
    for f in ok:
        if f.kind != "requirement":
            continue
        addr = [s["key"] for s in sections if f.id in s["requirement_ids"]]
        compliance.append({"requirement_id": f.id, "text": effective_value(f), "mandatory": bool(f.critical),
                           "source": f"{f.source_file} p.{f.source_page}", "sections": addr,
                           "status": "addressed" if addr else "unaddressed"})
    pv = create_version(db, opp, sections, compliance, actor_name, "AI draft from verified findings")
    log(db, opp.id, "proposal", f"Proposal draft v{pv.version_no} ready: {len(sections)} sections, "
        f"{sum(1 for c in compliance if c['status'] == 'addressed')}/{len(compliance)} requirements mapped.")
    return pv


# ── QA checklist (step 6) ──────────────────────────────────────────────────

def qa_checklist(db: Session, opp: Opportunity) -> list[dict]:
    pv = latest_version(db, opp.id)
    items = []

    def add(id_, label, ok, detail="", blocking=True):
        items.append({"id": id_, "label": label, "status": "pass" if ok else ("fail" if blocking else "warn"),
                      "detail": detail, "blocking": blocking})

    if not pv:
        return [{"id": "version", "label": "A proposal version exists", "status": "fail", "detail": "", "blocking": True}]
    valid = {(a.gate, a.proposal_version) for a in db.query(Approval).filter(
        Approval.opp_id == opp.id, Approval.valid.is_(True), Approval.decision == "approved").all()}
    has = lambda g, v=None: any(x[0] == g and (v is None or x[1] == v) for x in valid)
    empty = [s["title"] for s in pv.sections if not str(s.get("content", "")).strip()]
    add("sections", "All proposal sections have content", not empty, ", ".join(empty))
    add("g2", "Engineering validation approved (still valid)", has("g2"))
    add("g_prop", f"Proposal content approved for v{pv.version_no}", has("g_prop", pv.version_no))
    add("g3", f"Commercial approval recorded for v{pv.version_no}", has("g3", pv.version_no))
    crit = g2_blockers(db, opp.id)
    add("critical", "No unresolved critical findings / High RFIs", not crit, "; ".join(crit[:3]))
    tot = commercial_total(pv.commercial)["total"]
    add("fees", "Fees entered by an authorised commercial lead", tot > 0, f"Total {tot}")
    un = [c for c in pv.compliance if c["mandatory"] and c["status"] == "unaddressed"]
    add("mandatory", "Every mandatory requirement is mapped to a section", not un, f"{len(un)} unmapped", blocking=False)
    ph = sum(1 for s in pv.sections if s.get("placeholder"))
    add("placeholders", "No '[AB to ...]' placeholders left", ph == 0, f"{ph} section(s) still contain placeholders", blocking=False)
    cites = sum(len(s.get("unsupported_citations", [])) for s in pv.sections)
    add("citations", "No citations to unverified items were needed", cites == 0, f"{cites} removed", blocking=False)
    openh = [r for r in current_rfis(db, opp.id) if r.priority == "High" and r.status in OPEN_RFI]
    add("rfis", "High-priority RFIs are answered or carried as assumptions", not openh,
        f"{len(openh)} open - listed under dependencies in the proposal", blocking=False)
    return items
